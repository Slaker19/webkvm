// ErrClusterFirewallDisabled is returned when an apply is attempted with a
// profile whose Enabled flag is false. The profile ships disabled so an
// upgrade never takes over the host input chain by surprise.
var ErrClusterFirewallDisabled = errors.New("cluster firewall is disabled")

// ErrNoPendingClusterApply is returned by Confirm/Rollback when no apply is
// in flight.
var ErrNoPendingClusterApply = errors.New("no cluster firewall apply is pending")

// ClusterProfile is the input of the cluster-wide default-deny ruleset. It
// deliberately contains no host-specific data (no interface enumeration):
// the same profile renders byte-identical rules on all three nodes.
type ClusterProfile struct {
	Enabled             bool     `json:"enabled"`
	ClusterCIDR         string   `json:"cluster_cidr"`
	ManagementCIDRs     []string `json:"management_cidrs"`
	Bridges             []string `json:"bridges"`
	EnableLiveMigration bool     `json:"enable_live_migration"`
	MigrationPorts      string   `json:"migration_ports"`
	WebPort             int      `json:"web_port"`
	SSHPort             int      `json:"ssh_port"`
}

// DefaultClusterProfile is the baseline. Enabled=false and the networks are
// empty on purpose: the cluster CIDR and management networks come from
// settings (ha.cluster_cidr / ha.management_cidrs), never from a lab.
func DefaultClusterProfile() ClusterProfile {
	return ClusterProfile{
		Enabled:             false,
		ClusterCIDR:         "",
		ManagementCIDRs:     []string{},
		Bridges:             []string{"incusbr0", "virbr0"},
		EnableLiveMigration: true,
		MigrationPorts:      "49152-49215",
		WebPort:             8080,
		SSHPort:             22,
	}
}

var clusterBridgeRE = regexp.MustCompile(`^[A-Za-z0-9_.-]{1,15}$`)
var clusterPortSpecRE = regexp.MustCompile(`^[0-9]+(-[0-9]+)?(,[0-9]+(-[0-9]+)?)*$`)

func normalizeClusterProfile(p ClusterProfile) ClusterProfile {
	p.ManagementCIDRs = uniqueSorted(p.ManagementCIDRs)
	p.Bridges = uniqueSorted(p.Bridges)
	return p
}

func uniqueSorted(in []string) []string {
	seen := make(map[string]bool, len(in))
	out := make([]string, 0, len(in))
	for _, v := range in {
		v = strings.TrimSpace(v)
		if v == "" || seen[v] {
			continue
		}
		seen[v] = true
		out = append(out, v)
	}
	sort.Strings(out)
	return out
}

// ValidateClusterProfile rejects anything the renderer cannot turn into a
// safe nftables transaction.
func ValidateClusterProfile(p ClusterProfile) error {
	if strings.TrimSpace(p.ClusterCIDR) == "" {
		return errors.New("cluster_cidr is required: set ha.cluster_cidr in settings or send it in the profile")
	}
	if _, _, err := net.ParseCIDR(strings.TrimSpace(p.ClusterCIDR)); err != nil {
		return fmt.Errorf("cluster_cidr %q: %w", p.ClusterCIDR, err)
	}
	if len(p.ManagementCIDRs) == 0 {
		return errors.New("management_cidrs must contain at least one CIDR: set ha.management_cidrs in settings or send it in the profile")
	}
	for _, c := range p.ManagementCIDRs {
		if _, _, err := net.ParseCIDR(strings.TrimSpace(c)); err != nil {
			return fmt.Errorf("management cidr %q: %w", c, err)
		}
	}
	if len(p.Bridges) == 0 {
		return errors.New("bridges must contain at least one interface")
	}
	for _, b := range p.Bridges {
		if !clusterBridgeRE.MatchString(strings.TrimSpace(b)) {
			return fmt.Errorf("invalid bridge name %q", b)
		}
	}
	if p.WebPort < 1 || p.WebPort > 65535 {
		return fmt.Errorf("web_port %d out of range", p.WebPort)
	}
	if p.SSHPort < 1 || p.SSHPort > 65535 {
		return fmt.Errorf("ssh_port %d out of range", p.SSHPort)
	}
	if p.EnableLiveMigration {
		if !clusterPortSpecRE.MatchString(strings.TrimSpace(p.MigrationPorts)) {
			return fmt.Errorf("migration_ports %q: want e.g. 49152-49215", p.MigrationPorts)
		}
		for _, part := range strings.Split(p.MigrationPorts, ",") {
			lo, hi := part, part
			if i := strings.IndexByte(part, '-'); i >= 0 {
				lo, hi = part[:i], part[i+1:]
			}
			l, err1 := strconv.Atoi(lo)
			h, err2 := strconv.Atoi(hi)
			if err1 != nil || err2 != nil || l < 1 || h > 65535 || l > h {
				return fmt.Errorf("migration_ports %q: invalid range", p.MigrationPorts)
			}
		}
	}
	return nil
}

// RenderClusterRuleset returns the full default-deny table. The output is
// deterministic for a given profile (CIDRs and bridges sorted), so the same
// file can be applied on every node.
func RenderClusterRuleset(p ClusterProfile) (string, error) {
	if err := ValidateClusterProfile(p); err != nil {
		return "", err
	}
	p = normalizeClusterProfile(p)

	var b strings.Builder
	b.WriteString("# Generated by webkvm — cluster firewall (default deny). Do not edit.\n")
	b.WriteString("table inet webkvm_cluster\n")
	b.WriteString("delete table inet webkvm_cluster\n")
	b.WriteString("table inet webkvm_cluster {\n")
	fmt.Fprintf(&b, "\tset mgmt { type ipv4_addr; flags interval; auto-merge; elements = { %s } }\n",
		strings.Join(p.ManagementCIDRs, ", "))
	fmt.Fprintf(&b, "\tset cluster { type ipv4_addr; flags interval; auto-merge; elements = { %s } }\n",
		p.ClusterCIDR)
	b.WriteString("\tchain input {\n")
	b.WriteString("\t\ttype filter hook input priority filter; policy drop;\n")
	b.WriteString("\t\tct state established,related accept\n")
	b.WriteString("\t\tiif lo accept\n")
	b.WriteString("\t\ticmp type { echo-request, destination-unreachable, time-exceeded, parameter-problem } accept\n")
	b.WriteString("\t\ticmpv6 type { destination-unreachable, packet-too-big, time-exceeded, parameter-problem, nd-router-solicit, nd-router-advert, nd-neighbor-solicit, nd-neighbor-advert, mld2-listener-report } accept\n")
	for _, br := range p.Bridges {
		fmt.Fprintf(&b, "\t\tiifname %q udp dport 67 accept\n", br)
		fmt.Fprintf(&b, "\t\tiifname %q udp dport 53 accept\n", br)
		fmt.Fprintf(&b, "\t\tiifname %q tcp dport 53 accept\n", br)
		fmt.Fprintf(&b, "\t\tiifname %q udp dport 547 accept\n", br)
	}
	// Cluster-only services: Incus API + dqlite, pcsd, LINSTOR, DRBD.
	b.WriteString("\t\tip saddr @cluster tcp dport { 8443, 2224, 3366, 3370, 7000 } accept\n")
	b.WriteString("\t\tip saddr @cluster udp dport 5405 accept\n")
	if p.EnableLiveMigration {
		fmt.Fprintf(&b, "\t\tip saddr @cluster tcp dport %s accept\n", strings.TrimSpace(p.MigrationPorts))
	}
	// Admin access. rpcbind 111 and VNC 5900 are intentionally absent:
	// 111 is dropped by the policy and 5900 only listens on loopback.
	fmt.Fprintf(&b, "\t\tip saddr @mgmt tcp dport { %d, %d } accept\n", p.SSHPort, p.WebPort)
	b.WriteString("\t}\n}\n")
	return b.String(), nil
}

// CanonicalClusterProfilePath is the per-node source of truth for the
// cluster firewall. It lives outside DATA_DIR on purpose: a Pacemaker
// standby does not mount the DRBD volume, and the profile must be present
// there for the clone resource to apply it after a failover.
// WEBKVM_CLUSTER_FIREWALL_PROFILE overrides it for tests and non-standard
// installs.
func CanonicalClusterProfilePath() string {
	if p := strings.TrimSpace(os.Getenv("WEBKVM_CLUSTER_FIREWALL_PROFILE")); p != "" {
		return p
	}
	return "/etc/webkvm/cluster-firewall.json"
}

// ClusterProfileFile is the on-disk shape. Version is written by the active
// node and must grow monotonically; SHA256 covers the normalized profile and
// lets every node detect a truncated or tampered copy before applying it.
type ClusterProfileFile struct {
	Version int64          `json:"version"`
	SHA256  string         `json:"sha256"`
	Profile ClusterProfile `json:"profile"`
}

// ProfileSHA256 returns the hex fingerprint of the normalized profile.
func ProfileSHA256(p ClusterProfile) (string, error) {
	p = normalizeClusterProfile(p)
	data, err := json.Marshal(p)
	if err != nil {
		return "", err
	}
	sum := sha256.Sum256(data)
	return hex.EncodeToString(sum[:]), nil
}

// writeFileAtomic writes data through a temp file in the same directory,
// fsyncs it and the directory, then renames. A crash leaves either the old
// or the new file, never a partial one.
func writeFileAtomic(path string, data []byte, perm os.FileMode) error {
	dir := filepath.Dir(path)
	if err := os.MkdirAll(dir, 0o700); err != nil {
		return err
	}
	f, err := os.CreateTemp(dir, filepath.Base(path)+".tmp-*")
	if err != nil {
		return err
	}
	tmp := f.Name()
	defer os.Remove(tmp)
	if err := f.Chmod(perm); err != nil {
		f.Close()
		return err
	}
	if _, err := f.Write(data); err != nil {
		f.Close()
		return err
	}
	if err := f.Sync(); err != nil {
		f.Close()
		return err
	}
	if err := f.Close(); err != nil {
		return err
	}
	if err := os.Rename(tmp, path); err != nil {
		return err
	}
	if d, err := os.Open(dir); err == nil {
		_ = d.Sync()
		_ = d.Close()
	}
	return nil
}

func parseClusterProfileFile(data []byte) (ClusterProfileFile, error) {
	var raw struct {
		Version int64           `json:"version"`
		SHA256  string          `json:"sha256"`
		Profile *ClusterProfile `json:"profile"`
	}
	if err := json.Unmarshal(data, &raw); err != nil {
		return ClusterProfileFile{}, err
	}
	var file ClusterProfileFile
	if raw.Profile != nil {
		file = ClusterProfileFile{Version: raw.Version, SHA256: raw.SHA256, Profile: *raw.Profile}
	} else {
		// Legacy F-A file: the document is the profile itself.
		var p ClusterProfile
		if err := json.Unmarshal(data, &p); err != nil {
			return ClusterProfileFile{}, err
		}
		file = ClusterProfileFile{Version: 1, Profile: p}
	}
	file.Profile = normalizeClusterProfile(file.Profile)
	if err := ValidateClusterProfile(file.Profile); err != nil {
		return ClusterProfileFile{}, err
	}
	hash, err := ProfileSHA256(file.Profile)
	if err != nil {
		return ClusterProfileFile{}, err
	}
	if file.SHA256 != "" && file.SHA256 != hash {
		return ClusterProfileFile{}, errors.New("profile hash does not match the declared sha256")
	}
	file.SHA256 = hash
	return file, nil
}

// parseClusterProfileFileStrict requires the declared sha256. Receive and
// sync use this variant: an unsigned file must never reach the kernel.
func parseClusterProfileFileStrict(data []byte) (ClusterProfileFile, error) {
	var declared struct {
		SHA256 string `json:"sha256"`
	}
	if err := json.Unmarshal(data, &declared); err != nil {
		return ClusterProfileFile{}, err
	}
	if strings.TrimSpace(declared.SHA256) == "" {
		return ClusterProfileFile{}, errors.New("profile is missing the required sha256")
	}
	return parseClusterProfileFile(data)
}

// LoadClusterProfileFileStrict is the receive/sync variant: a missing file
// still yields the disabled default (which has a computed hash), but any
// existing file must declare its sha256.
func LoadClusterProfileFileStrict(path string) (ClusterProfileFile, error) {
	data, err := os.ReadFile(path)
	if errors.Is(err, os.ErrNotExist) {
		return LoadClusterProfileFile(path)
	}
	if err != nil {
		return ClusterProfileFile{}, err
	}
	return parseClusterProfileFileStrict(data)
}

// LoadClusterProfileFile reads path. A missing file yields the default
// profile with version 0, so nothing can be applied until the admin
// publishes a profile.
func LoadClusterProfileFile(path string) (ClusterProfileFile, error) {
	data, err := os.ReadFile(path)
	if errors.Is(err, os.ErrNotExist) {
		p := normalizeClusterProfile(DefaultClusterProfile())
		hash, herr := ProfileSHA256(p)
		if herr != nil {
			return ClusterProfileFile{}, herr
		}
		return ClusterProfileFile{Version: 0, SHA256: hash, Profile: p}, nil
	}
	if err != nil {
		return ClusterProfileFile{}, err
	}
	return parseClusterProfileFile(data)
}

// LoadClusterProfile reads path. A missing file yields the default profile
// (disabled), so first boot cannot enable the firewall by accident.
func LoadClusterProfile(path string) (ClusterProfile, error) {
	file, err := LoadClusterProfileFile(path)
	if err != nil {
		return ClusterProfile{}, err
	}
	return file.Profile, nil
}

// SaveClusterProfile persists the profile atomically (0600), bumps the
// monotonic version and keeps the previous file as .prev for rollback.
func SaveClusterProfile(path string, p ClusterProfile) (ClusterProfileFile, error) {
	file, err := LoadClusterProfileFile(path)
	if err != nil && !errors.Is(err, os.ErrNotExist) {
		return ClusterProfileFile{}, err
	}
	if err := ValidateClusterProfile(p); err != nil {
		return ClusterProfileFile{}, err
	}
	p = normalizeClusterProfile(p)
	hash, err := ProfileSHA256(p)
	if err != nil {
		return ClusterProfileFile{}, err
	}
	file.Profile = p
	file.SHA256 = hash
	file.Version++
	if file.Version < 1 {
		file.Version = 1
	}
	if current, rerr := os.ReadFile(path); rerr == nil {
		if werr := writeFileAtomic(path+".prev", current, 0o600); werr != nil {
			return ClusterProfileFile{}, werr
		}
	}
	data, err := json.MarshalIndent(file, "", "  ")
	if err != nil {
		return ClusterProfileFile{}, err
	}
	if err := writeFileAtomic(path, data, 0o600); err != nil {
		return ClusterProfileFile{}, err
	}
	return file, nil
}
